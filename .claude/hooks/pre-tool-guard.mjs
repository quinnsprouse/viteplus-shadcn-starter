// PreToolUse guard: blocks the handful of agent actions that no lint rule can express.
// Denied: edits to generated or tool-owned files, hook bypasses, and package managers other than
// npm and Vite+. Destructive git commands are escalated to the human with "ask". Everything else
// passes through untouched.
import { readFileSync } from "node:fs";
import { isAbsolute, relative, resolve } from "node:path";

const projectRoot = process.env.CLAUDE_PROJECT_DIR ?? process.cwd();

const protectedPaths = [
  {
    test: (path) => path === "src/routeTree.gen.ts",
    reason:
      "src/routeTree.gen.ts is generated by TanStack Router. Add or edit a file under src/routes/ and it regenerates on the next dev or build.",
  },
  {
    test: (path) => path === "package-lock.json",
    reason:
      "package-lock.json is owned by npm. Change package.json with `vp add <pkg>` or `npm install <pkg>@<version>` and let npm rewrite the lockfile.",
  },
  {
    test: (path) => path.startsWith(".vite-hooks/_/"),
    reason:
      ".vite-hooks/_ is installed by Vite+. Edit the tracked scripts in .vite-hooks/ instead and run `npm run setup`.",
  },
  {
    test: (path) => path.startsWith(".output/") || path.startsWith("node_modules/"),
    reason:
      "Build output and node_modules are not source. Change the input that produced this file instead.",
  },
];

const guardedCommands = [
  {
    test: /\bgit\s+(?:-\S+\s+)*commit\b.*\s(?:--no-verify|-n)\b/,
    decision: "deny",
    reason:
      "Committing with --no-verify skips the pre-commit gate. Fix the reported problems, or ask a human to bypass the hook.",
  },
  {
    test: /\bgit\s+(?:-\S+\s+)*push\b.*\s(?:--force|-f)\b/,
    decision: "ask",
    reason:
      "Force pushes rewrite shared history. Prefer --force-with-lease, and only when a human has asked for it.",
  },
  {
    test: /\bgit\s+(?:-\S+\s+)*(?:reset\s+--hard|checkout\s+--\s+\.|restore\s+(?:--worktree\s+)?\.|clean\s+-[a-zA-Z]*f)/,
    decision: "ask",
    reason: "This discards uncommitted work. A human should confirm destructive git commands.",
  },
  {
    test: /\b(?:pnpm|yarn|bun)\s+(?:add|install|i|remove|rm)\b/,
    decision: "deny",
    reason:
      "This project is npm-only (see devEngines in package.json). Use `vp add <pkg>` or `npm install`.",
  },
  {
    test: /\bnpx\s+(?:oxlint|oxfmt|vitest|eslint|prettier)\b/,
    decision: "deny",
    reason:
      "Use the Vite+ wrappers: `vp lint`, `vp fmt`, `vp test`. Direct oxlint/vitest calls skip the project configuration.",
  },
];

function decide(decision, reason) {
  process.stdout.write(
    `${JSON.stringify({
      hookSpecificOutput: {
        hookEventName: "PreToolUse",
        permissionDecision: decision,
        permissionDecisionReason: reason,
      },
    })}\n`,
  );
  process.exit(0);
}

function projectPath(filePath) {
  const absolute = isAbsolute(filePath) ? filePath : resolve(projectRoot, filePath);
  const path = relative(projectRoot, absolute).replaceAll("\\", "/");
  return path.startsWith("..") ? null : path;
}

try {
  const input = JSON.parse(readFileSync(0, "utf8"));
  if (input.hook_event_name !== "PreToolUse") process.exit(0);

  if (["Edit", "Write", "MultiEdit", "NotebookEdit"].includes(input.tool_name)) {
    const target = input.tool_input?.file_path ?? input.tool_input?.notebook_path;
    if (typeof target !== "string") process.exit(0);
    const path = projectPath(target);
    if (path === null) process.exit(0);
    const hit = protectedPaths.find((rule) => rule.test(path));
    if (hit) decide("deny", hit.reason);
  }

  if (input.tool_name === "Bash" && typeof input.tool_input?.command === "string") {
    const command = input.tool_input.command;
    const hit = guardedCommands.find((rule) => rule.test.test(command));
    if (hit) decide(hit.decision, hit.reason);
  }
} catch {
  // A guard that cannot parse its input must not block the agent.
}
process.exit(0);
